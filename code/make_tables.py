"""Emit the LaTeX bodies of the result tables from the aggregated runs.

The manuscript includes these files, so every number in the paper is produced by
the code in this directory and no value is typed by hand.
"""
import json
import numpy as np

AGG = json.load(open('../results/agg.json'))
CLFS = ['LDA', 'QDA', 'NB', 'KNN', 'RF', 'HGB', 'MLP']
OUT = '../tables/'
import os
os.makedirs(OUT, exist_ok=True)


def star(p):
    return r'\,$^{*}$' if p is not None and p < 0.05 else r'\phantom{\,$^{*}$}'


HEAD6 = (r'\begin{tabular}{@{}lccccc@{}}' + '\n' + r'\toprule' + '\n' +
         r'\textbf{Classifier} & \textbf{Pooled} & \textbf{+ feature} & \textbf{Part.} & '
         r'$\boldsymbol{\Delta}$\textbf{ pool} & $\boldsymbol{\Delta}$\textbf{ feat}' + '\\\\')
FOOT = r'\bottomrule' + '\n' + r'\end{tabular}'


def main_table(ds, fname):
    """Accuracy of the four methods and the two paired differences, per level."""
    lines = [HEAD6]
    levels = list(AGG[ds])
    for lv in levels:
        o = AGG[ds][lv]
        lines.append(r'\midrule')
        lines.append(r'\multicolumn{6}{l}{$%s$: \textit{%s}, $M=%d$}\\' %
                     (lv.split()[0].replace('L', 'L_'), ' '.join(lv.split()[1:]).replace('x', r'$\times$'),
                      o['n_regimes']))
        for r in o['recs']:
            lines.append('%s & %.2f & %.2f & %.2f & %s%s & %s%s \\\\' % (
                r['clf'], r['pool'], r['feat'], r['part'],
                f"{r['d_pool']:+.2f}", star(r.get('p_pool')),
                f"{r['d_feat']:+.2f}", star(r.get('p_feat'))))
        if o['sel'] is not None:
            lines.append(r'\textit{selection} & \multicolumn{2}{c}{---} & %.2f & \multicolumn{2}{c}{---}\\' % o['sel'])
    lines.append(FOOT)
    open(OUT + fname, 'w').write('\n'.join(lines) + '\n')
    return len(lines)


def chrono_table(fname):
    lines = [HEAD6]
    for ds in AGG:
        for lv in AGG[ds]:
            o = AGG[ds][lv]
            if not o['chrono']:
                continue
            lines.append(r'\midrule')
            lines.append(r'\multicolumn{6}{l}{%s, $%s$: \textit{%s}}\\' %
                         (ds, lv.split()[0].replace('L', 'L_'),
                          ' '.join(lv.split()[1:]).replace('x', r'$\times$')))
            for r in o['chrono']:
                lines.append('%s & %.2f & %.2f & %.2f & %+.2f & %+.2f \\\\' % (
                    r['clf'], r['pool'], r['feat'], r['part'], r['d_pool'], r['d_feat']))
            if o['chrono_sel'] is not None:
                lines.append(r'\textit{selection} & \multicolumn{2}{c}{---} & %.2f & \multicolumn{2}{c}{---}\\'
                             % o['chrono_sel'])
    lines.append(FOOT)
    open(OUT + fname, 'w').write('\n'.join(lines) + '\n')


def summary_numbers(fname):
    """Macros with the headline numbers, so the text cannot drift from the tables."""
    par, flex = {'pool': [], 'feat': []}, {'pool': [], 'feat': []}
    for ds in AGG:
        for lv in AGG[ds]:
            for r in AGG[ds][lv]['recs']:
                tgt = par if r['clf'] in ('LDA', 'QDA', 'NB') else flex
                tgt['pool'].append(r['d_pool']); tgt['feat'].append(r['d_feat'])
    with open(OUT + fname, 'w') as fh:
        fh.write('%% generated by make_tables.py\n')
        fh.write(r'\newcommand{\parGainPool}{%.1f}' % np.mean(par['pool']) + '\n')
        fh.write(r'\newcommand{\flexGainPool}{%.1f}' % np.mean(flex['pool']) + '\n')
        fh.write(r'\newcommand{\parGainFeat}{%.1f}' % np.mean(par['feat']) + '\n')
        fh.write(r'\newcommand{\flexGainFeat}{%.1f}' % np.mean(flex['feat']) + '\n')


if __name__ == '__main__':
    for ds in AGG:
        main_table(ds, 'paired_%s.tex' % ds.lower())
    chrono_table('chrono.tex')
    summary_numbers('numbers.tex')
    print('tables written to', OUT)
